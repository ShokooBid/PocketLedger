import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import { format, resolveConfig } from "prettier";
import { defaultCategoryCatalog } from "../apps/api/src/categories/catalog.v1.ts";

// Build-time only. The app bundles static SVG XML and never imports API code,
// reads filesystem paths at runtime or fetches arbitrary SVG URLs.
const source = new URL(
  "../apps/mobile/assets/category-icons/",
  import.meta.url
);
const manifest = JSON.parse(
  await readFile(new URL("manifest.json", source), "utf8")
);
const registry = {};
const catalog = defaultCategoryCatalog.items;
const roots = new Map(
  catalog.filter((item) => !item.parentKey).map((item) => [item.key, item.name])
);
for (const item of catalog) {
  if (!/^[a-z][a-z0-9_-]{0,39}$/.test(item.iconKey) || registry[item.iconKey])
    throw new Error("Catalog icon keys must be valid and unique.");
  const matches = manifest.filter((entry) =>
    item.parentKey
      ? entry.category === roots.get(item.parentKey) &&
        entry.subcategory === item.name
      : entry.category === item.name && entry.subcategory === null
  );
  if (
    matches.length !== 1 ||
    path.basename(matches[0].filename) !== matches[0].filename
  )
    throw new Error(`Missing or ambiguous icon mapping for ${item.key}.`);
  const filename = matches[0].filename;
  const svg = await readFile(
    new URL(encodeURIComponent(filename), source),
    "utf8"
  );
  if (
    !svg.includes('viewBox="0 0 64 64"') ||
    /<!DOCTYPE|<!ENTITY|<script|<foreignObject|<image|(?:href|src)\s*=/i.test(
      svg
    )
  )
    throw new Error(`Unsupported SVG content for ${item.key}.`);
  registry[item.iconKey] = {
    defaultKey: item.key,
    filename,
    // Icons are decorative beside accessible text/button labels.
    xml: svg.replace(/\s(?:role|aria-label)="[^"]*"/g, "").trim()
  };
}
if (Object.keys(registry).length !== manifest.length)
  throw new Error("Every supplied SVG must have exactly one catalog mapping.");
const output = new URL(
  "../apps/mobile/src/category-icon-assets.ts",
  import.meta.url
);
await writeFile(
  output,
  await format(
    `// Generated by npm run icons:generate. Edit the catalog/SVG sources instead.\nexport const categoryIconAssets: Readonly<Record<string, { defaultKey: string; filename: string; xml: string }>> = ${JSON.stringify(registry, null, 2)};\n`,
    { ...(await resolveConfig(fileURLToPath(output))), parser: "typescript" }
  )
);

// This one-time trusted catalog upgrade is separate from normal provisioning,
// which intentionally preserves existing default rows verbatim.
if (process.argv.includes("--migration")) {
  const migration = new URL(
    "../apps/api/prisma/migrations/20261030040000_category_icons/migration.sql",
    import.meta.url
  );
  if (existsSync(migration))
    throw new Error("Refusing to overwrite an existing migration.");
  const quote = (value) => `'${value.replaceAll("'", "''")}'`;
  const values = Object.entries(registry)
    .map(
      ([iconKey, asset]) => `  (${quote(asset.defaultKey)}, ${quote(iconKey)})`
    )
    .join(",\n");
  await mkdir(new URL(".", migration), { recursive: true });
  await writeFile(
    migration,
    `-- Trusted, versioned catalog presentation update. No filesystem paths in DB.\nBEGIN;\n-- Hold the table lock until the immutable-default guard is enabled again.\nLOCK TABLE "Category" IN ACCESS EXCLUSIVE MODE;\nALTER TABLE "Category" DISABLE TRIGGER "Category_hierarchy";\nWITH icons(default_key, icon_key) AS (VALUES\n${values}\n)\nUPDATE "Category" c SET "iconKey" = icons.icon_key\nFROM icons WHERE c."isDefault" AND c."defaultKey" = icons.default_key\n  AND c."iconKey" IS DISTINCT FROM icons.icon_key;\nALTER TABLE "Category" ENABLE TRIGGER "Category_hierarchy";\nCOMMIT;\n`
  );
}
console.info(
  `Generated ${Object.keys(registry).length} bundled category icon mappings.`
);
